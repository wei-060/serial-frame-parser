#ifndef FRAME_H
#define FRAME_H

#include <stdint.h>

/* ------------------------------------------------------------
 * 帧格式
 *
 *   偏移    0     1     2      3      4      5 .. 4+N   5+N  6+N
 *         +-----+-----+------+------+------+-----------+-----+-----+
 *         | AA  | 55  | 地址 | 功能 | 长度 |   数据    | CRC | CRC |
 *         |     |     |      | 码   |  N   |           | 低  | 高  |
 *         +-----+-----+------+------+------+-----------+-----+-----+
 *           +-------+   +-----------------------------+
 *            帧头(2)      参与 CRC 计算的 (3 + N) 字节
 *
 *   整帧长度 = 7 + N
 *   CRC 计算范围：地址 → 数据段最后一个字节（不含帧头，不含 CRC 自己）
 *   CRC 存放顺序：低字节在前（小端）
 * ------------------------------------------------------------ */

/* 一帧的解析结果 */
typedef struct {
    uint8_t  addr;        /* 地址 */
    uint8_t  func;        /* 功能码 */
    uint8_t  len;         /* 数据段长度 N */
    uint8_t  data[256];   /* 数据段内容（LEN 是 1 字节，最大 255） */
    uint16_t crc_ok;      /* 1 = CRC 校验通过，0 = 不通过 */
} Frame;


/* 解析一个「完整的帧」
 *
 * 前提：传入的 frame 指向一个完整帧（长度由调用者保证）。
 * 返回：1 = 帧结构完整（CRC 是否正确看 out->crc_ok）
 *       0 = 帧头不是 AA 55，根本不是一帧
 *
 * CRC 错时仍返回 1：「数据被篡改」与「压根不是一帧」属于两种不同情形，
 * 调用者据此区分处理。
 */
int parse_frame(const uint8_t *frame, Frame *out);


/* 从字节流中提取所有合法帧（处理粘包 / 断包 / 噪声 / 坏帧 / 假帧头）
 *
 * 参数：
 *   stream, len : 输入的字节流
 *   out, max    : 结果存放处，最多装 max 帧
 *   consumed    : 【输出】扫描到的位置。
 *                 consumed 之前的字节已处理完，可安全丢弃；
 *                 consumed 之后的字节需保留（可能是没收完的半帧）。
 * 返回：成功提取的帧数
 */
int extract_frames(const uint8_t *stream, uint16_t len,
                   Frame *out, int max, uint16_t *consumed);

#endif /* FRAME_H */
